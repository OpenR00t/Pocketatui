//! Episode transcripts: the publisher's or Pocket Casts' own (WebVTT / SRT / JSON), or
//! made locally by Whisper. All end up as a list of timed cues.

use std::path::PathBuf;

use serde::{Deserialize, Serialize};
use serde_json::Value;

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Cue {
    pub start: f64,
    pub end: f64,
    pub text: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Source {
    /// Supplied by the podcast in its feed.
    Publisher,
    /// Generated by Pocket Casts.
    PocketCasts,
    /// Made on this machine.
    Whisper,
}

impl Source {
    pub fn label(self) -> &'static str {
        match self {
            Self::Publisher => "Publisher",
            Self::PocketCasts => "Pocket Casts",
            Self::Whisper => "Whisper",
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Transcript {
    pub source: Source,
    pub cues: Vec<Cue>,
    /// Whisper only: stretches of the episode already transcribed, in seconds.
    #[serde(default)]
    pub covered: Vec<(f64, f64)>,
    /// Whisper only: the model that made it.
    #[serde(default)]
    pub model: String,
    /// Lining up a transcript made from a different copy of the audio (ads are often
    /// inserted per download): `(audio time, offset)` pairs, sorted. From each audio
    /// time on, transcript time = audio time + offset. Not saved: the next download
    /// may have different ads.
    #[serde(skip)]
    pub anchors: Vec<(f64, f64)>,
}

impl Transcript {
    pub fn new(source: Source, cues: Vec<Cue>) -> Self {
        Self {
            source,
            cues,
            covered: Vec::new(),
            model: String::new(),
            anchors: Vec::new(),
        }
    }

    /// Transcript-minus-audio offset in effect at audio time `audio`.
    pub fn offset_at(&self, audio: f64) -> f64 {
        let i = self.anchors.partition_point(|(a, _)| *a <= audio);
        match (i.checked_sub(1), self.anchors.first()) {
            (Some(j), _) => self.anchors[j].1,
            (None, Some(first)) => first.1, // before the first anchor: best guess
            (None, None) => 0.0,
        }
    }

    /// Audio time at which transcript time `t` is heard.
    pub fn to_audio(&self, t: f64) -> f64 {
        // The last stretch whose transcript times start at or before `t`.
        let mut audio = t - self.offset_at(f64::NEG_INFINITY);
        for &(a, off) in &self.anchors {
            if a + off <= t {
                audio = t - off;
            }
        }
        audio
    }

    /// Record that audio time `audio` lines up with transcript time `audio + offset`,
    /// replacing anchors close by.
    pub fn set_anchor(&mut self, audio: f64, offset: f64) {
        self.anchors.retain(|(a, _)| (a - audio).abs() > 20.0);
        self.anchors.push((audio, offset));
        self.anchors.sort_by(|a, b| a.0.total_cmp(&b.0));
    }

    /// Index of the cue being spoken at audio time `pos` (the last one that has started).
    pub fn current(&self, pos: f64) -> Option<usize> {
        let t = pos + self.offset_at(pos);
        let i = self.cues.partition_point(|c| c.start <= t + 0.05);
        i.checked_sub(1)
    }

    /// Add Whisper cues for `span`, keeping cues sorted and spans merged.
    pub fn add_whisper(&mut self, span: (f64, f64), cues: Vec<Cue>) {
        self.cues.retain(|c| c.start < span.0 || c.start >= span.1);
        self.cues.extend(cues);
        self.cues.sort_by(|a, b| a.start.total_cmp(&b.start));
        self.covered.push(span);
        self.covered = merge_spans(std::mem::take(&mut self.covered));
    }

    /// End of the transcribed stretch containing `pos`, if `pos` is covered.
    pub fn covered_until(&self, pos: f64) -> Option<f64> {
        self.covered
            .iter()
            .find(|(a, b)| *a <= pos + 0.5 && pos < *b)
            .map(|(_, b)| *b)
    }
}

pub fn merge_spans(mut v: Vec<(f64, f64)>) -> Vec<(f64, f64)> {
    v.sort_by(|a, b| a.0.total_cmp(&b.0));
    let mut out: Vec<(f64, f64)> = Vec::new();
    for (a, b) in v {
        match out.last_mut() {
            Some(last) if a <= last.1 + 0.5 => last.1 = last.1.max(b),
            _ => out.push((a, b)),
        }
    }
    out
}

/// One normalised word of a transcript: lowercase letters and digits only.
#[derive(Debug, Clone, PartialEq)]
pub struct Word {
    pub text: String,
    /// Estimated time (spread evenly across its cue).
    pub time: f64,
    /// Index of the cue it came from.
    pub cue: usize,
}

/// Words of `cues` with times and cue indexes.
pub fn words(cues: &[Cue]) -> Vec<Word> {
    timed_words(cues)
        .into_iter()
        .zip(cue_of_each_word(cues))
        .map(|((text, time), cue)| Word { text, time, cue })
        .collect()
}

fn cue_of_each_word(cues: &[Cue]) -> Vec<usize> {
    cues.iter()
        .enumerate()
        .flat_map(|(i, c)| std::iter::repeat_n(i, normalised(&c.text).count()))
        .collect()
}

fn normalised(text: &str) -> impl Iterator<Item = String> + '_ {
    text.split_whitespace()
        .map(|w| {
            w.chars()
                .filter(|ch| ch.is_alphanumeric())
                .collect::<String>()
                .to_lowercase()
        })
        .filter(|w| !w.is_empty())
}

/// Words of `cues` with times, spread evenly across each cue.
fn timed_words(cues: &[Cue]) -> Vec<(String, f64)> {
    let mut out = Vec::new();
    for c in cues {
        let words: Vec<String> = normalised(&c.text).collect();
        let n = words.len().max(1) as f64;
        let span = (c.end - c.start).max(0.0);
        for (i, w) in words.into_iter().enumerate() {
            out.push((w, c.start + span * i as f64 / n));
        }
    }
    out
}

/// Find the offset (transcript time - audio time) that lines `sample` (cues transcribed
/// from the real audio, in audio time) up with `transcript`, by matching runs of four
/// words and voting on how far apart they are. Only offsets within `window` seconds of
/// `guess` count. `None` if nothing matches convincingly (e.g. the sample is an ad).
pub fn align(transcript: &[Cue], sample: &[Cue], guess: f64, window: f64) -> Option<f64> {
    const N: usize = 4;
    let tw = timed_words(transcript);
    let sw = timed_words(sample);
    if sw.len() < N + 2 {
        return None;
    }
    let mut index: std::collections::HashMap<String, Vec<f64>> = std::collections::HashMap::new();
    for g in tw.windows(N) {
        let key = g
            .iter()
            .map(|(w, _)| w.as_str())
            .collect::<Vec<_>>()
            .join(" ");
        index.entry(key).or_default().push(g[0].1);
    }
    let mut deltas = Vec::new();
    for g in sw.windows(N) {
        let key = g
            .iter()
            .map(|(w, _)| w.as_str())
            .collect::<Vec<_>>()
            .join(" ");
        for &t in index.get(&key).into_iter().flatten() {
            let d = t - g[0].1;
            if (d - guess).abs() <= window {
                deltas.push(d);
            }
        }
    }
    if deltas.len() < 3 {
        return None;
    }
    // The 3-second window holding the most votes.
    deltas.sort_by(f64::total_cmp);
    let (mut best, mut best_n) = (0usize, 0usize);
    for i in 0..deltas.len() {
        let n = deltas[i..]
            .iter()
            .take_while(|d| **d <= deltas[i] + 3.0)
            .count();
        if n > best_n {
            (best, best_n) = (i, n);
        }
    }
    if best_n < 3 || (best_n as f64) < 0.5 * deltas.len() as f64 {
        return None;
    }
    let cluster = &deltas[best..best + best_n];
    Some(cluster[cluster.len() / 2])
}

/// A transcript file an episode offers.
#[derive(Debug, Clone, PartialEq)]
pub struct Offer {
    pub url: String,
    pub mime: String,
    pub source: Source,
}

/// The transcript files listed for one episode in a show-notes record. Publisher
/// files come first, then Pocket Casts' generated ones; formats we can't read are left out.
pub fn offers(episode: &Value) -> Vec<Offer> {
    let mut out = Vec::new();
    for (key, source) in [
        ("transcripts", Source::Publisher),
        ("pocket_casts_transcripts", Source::PocketCasts),
    ] {
        let Some(list) = episode.get(key).and_then(Value::as_array) else {
            continue;
        };
        for t in list {
            let url = t.get("url").and_then(Value::as_str).unwrap_or_default();
            let mime = t.get("type").and_then(Value::as_str).unwrap_or_default();
            if !url.is_empty() && format_of(mime, url).is_some() {
                out.push(Offer {
                    url: url.into(),
                    mime: mime.into(),
                    source,
                });
            }
        }
    }
    out
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Format {
    Vtt,
    Srt,
    Json,
}

pub fn format_of(mime: &str, url: &str) -> Option<Format> {
    let m = mime.to_ascii_lowercase();
    let u = url.to_ascii_lowercase();
    let u = u.split('?').next().unwrap_or_default();
    if m.contains("vtt") || u.ends_with(".vtt") {
        Some(Format::Vtt)
    } else if m.contains("srt") || m.contains("subrip") || u.ends_with(".srt") {
        Some(Format::Srt)
    } else if m.contains("json") || u.ends_with(".json") {
        Some(Format::Json)
    } else {
        None
    }
}

/// Parse a transcript file into cues.
pub fn parse(body: &str, format: Format) -> Vec<Cue> {
    let mut cues = match format {
        Format::Vtt | Format::Srt => parse_cues(body),
        Format::Json => parse_json(body),
    };
    cues.retain(|c| !c.text.is_empty());
    cues.sort_by(|a, b| a.start.total_cmp(&b.start));
    cues
}

/// WebVTT and SRT share the same shape: blocks with a `start --> end` line then text.
fn parse_cues(body: &str) -> Vec<Cue> {
    let body = body.replace("\r\n", "\n");
    let mut cues = Vec::new();
    for block in body.split("\n\n") {
        let mut lines = block.lines().skip_while(|l| !l.contains("-->"));
        let Some(timing) = lines.next() else { continue };
        let mut parts = timing.split("-->");
        let (Some(a), Some(b)) = (parts.next(), parts.next()) else {
            continue;
        };
        // "00:01.000 --> 00:02.500 align:start" → keep only the timestamps
        let b = b.split_whitespace().next().unwrap_or_default();
        let (Some(start), Some(end)) = (timestamp(a.trim()), timestamp(b)) else {
            continue;
        };
        let text = lines
            .map(strip_tags)
            .filter(|l| !l.is_empty())
            .collect::<Vec<_>>()
            .join(" ");
        cues.push(Cue { start, end, text });
    }
    cues
}

/// `hh:mm:ss.mmm`, `mm:ss.mmm` or SRT's `hh:mm:ss,mmm`.
fn timestamp(s: &str) -> Option<f64> {
    let s = s.replace(',', ".");
    let parts: Vec<&str> = s.split(':').collect();
    let nums: Option<Vec<f64>> = parts.iter().map(|p| p.trim().parse::<f64>().ok()).collect();
    let nums = nums?;
    Some(match nums.as_slice() {
        [h, m, s] => h * 3600.0 + m * 60.0 + s,
        [m, s] => m * 60.0 + s,
        [s] => *s,
        _ => return None,
    })
}

/// Drop VTT markup like `<v Speaker>`, `<c.yellow>`, `<00:01.000>`; keep a speaker name.
fn strip_tags(line: &str) -> String {
    let mut out = String::new();
    let mut rest = line;
    while let Some(i) = rest.find('<') {
        out.push_str(&rest[..i]);
        let Some(j) = rest[i..].find('>') else {
            out.push_str(&rest[i..]);
            rest = "";
            break;
        };
        let tag = &rest[i + 1..i + j];
        if let Some(name) = tag.strip_prefix("v ") {
            out.push_str(name.trim());
            out.push_str(": ");
        }
        rest = &rest[i + j + 1..];
    }
    out.push_str(rest);
    out.replace("&amp;", "&")
        .replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&nbsp;", " ")
        .trim()
        .to_string()
}

/// The Podcasting 2.0 JSON transcript format: `{"segments":[{startTime,endTime,body,speaker}]}`.
fn parse_json(body: &str) -> Vec<Cue> {
    let Ok(v) = serde_json::from_str::<Value>(body) else {
        return Vec::new();
    };
    let segs = v
        .get("segments")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default();
    segs.iter()
        .filter_map(|s| {
            let start = s.get("startTime")?.as_f64()?;
            let end = s.get("endTime").and_then(Value::as_f64).unwrap_or(start);
            let text = s.get("body")?.as_str()?.trim().to_string();
            let text = match s.get("speaker").and_then(Value::as_str) {
                Some(sp) if !sp.is_empty() => format!("{sp}: {text}"),
                _ => text,
            };
            Some(Cue { start, end, text })
        })
        .collect()
}

/// `<uuid>.json` holds the episode's own transcript, `<uuid>.whisper.json` Whisper's.
fn cache_path(uuid: &str, whisper: bool) -> Option<PathBuf> {
    let dirs = directories::ProjectDirs::from("", "", "pocketatui")?;
    let dir = dirs.cache_dir().join("transcripts");
    std::fs::create_dir_all(&dir).ok()?;
    let safe: String = uuid
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '-')
        .collect();
    let ext = if whisper { "whisper.json" } else { "json" };
    Some(dir.join(format!("{safe}.{ext}")))
}

fn read(uuid: &str, whisper: bool) -> Option<Transcript> {
    let path = cache_path(uuid, whisper)?;
    let text = std::fs::read_to_string(&path).ok()?;
    crate::cache::touch(&path);
    serde_json::from_str(&text).ok()
}

/// The episode's own transcript, if cached.
pub fn load_cached(uuid: &str) -> Option<Transcript> {
    read(uuid, false).filter(|t| t.source != Source::Whisper)
}

/// Whisper's transcript so far, if any (older versions kept it in `<uuid>.json`).
pub fn load_whisper(uuid: &str) -> Option<Transcript> {
    read(uuid, true).or_else(|| read(uuid, false).filter(|t| t.source == Source::Whisper))
}

pub fn save_cached(uuid: &str, t: &Transcript) {
    let whisper = t.source == Source::Whisper;
    if let (Some(p), Ok(s)) = (cache_path(uuid, whisper), serde_json::to_string(t)) {
        let _ = std::fs::write(p, s);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn parses_vtt() {
        let vtt = "WEBVTT\n\n00:00.000 --> 00:03.260\nThis is the <v Guy Raz>show.\n\n1\n01:00:04.420 --> 01:00:06.820 align:start\nEach week,\ngroundbreaking &amp; new.\n";
        let c = parse(vtt, Format::Vtt);
        assert_eq!(c.len(), 2);
        assert_eq!(c[0].text, "This is the Guy Raz: show.");
        assert!((c[1].start - 3604.42).abs() < 1e-6);
        assert_eq!(c[1].text, "Each week, groundbreaking & new.");
    }

    #[test]
    fn parses_srt_and_json() {
        let srt = "1\r\n00:00:01,500 --> 00:00:02,000\r\nHello\r\n\r\n2\r\n00:00:03,000 --> 00:00:04,000\r\nWorld\r\n";
        let c = parse(srt, Format::Srt);
        assert_eq!((c[0].start, c[1].text.as_str()), (1.5, "World"));
        let j = r#"{"version":"1.0","segments":[{"speaker":"Ann","startTime":0.5,"endTime":1.0,"body":"Hi"}]}"#;
        assert_eq!(parse(j, Format::Json)[0].text, "Ann: Hi");
    }

    #[test]
    fn finds_current_and_merges_whisper_spans() {
        let mut t = Transcript::new(Source::Whisper, vec![]);
        let cue = |s: f64, txt: &str| Cue {
            start: s,
            end: s + 1.0,
            text: txt.into(),
        };
        t.add_whisper((30.0, 58.0), vec![cue(31.0, "b"), cue(40.0, "c")]);
        t.add_whisper((0.0, 30.0), vec![cue(1.0, "a")]);
        assert_eq!(t.covered, vec![(0.0, 58.0)]);
        assert_eq!(t.current(35.0), Some(1));
        assert_eq!(t.current(0.5), None);
        assert_eq!(t.covered_until(10.0), Some(58.0));
        assert_eq!(t.covered_until(60.0), None);
    }

    fn cues_from(text: &str, start: f64, secs_per_cue: f64, words_per_cue: usize) -> Vec<Cue> {
        let words: Vec<&str> = text.split_whitespace().collect();
        words
            .chunks(words_per_cue)
            .enumerate()
            .map(|(i, w)| {
                let s = start + i as f64 * secs_per_cue;
                Cue {
                    start: s,
                    end: s + secs_per_cue,
                    text: w.join(" "),
                }
            })
            .collect()
    }

    const TALK: &str = "the difference is the cord length on that forward element on the ferrari red bull \
        and mclaren is the same length as the forward two elements of the mercedes front wing so you know \
        mercedes got two elements to form the cord length and the problem with that is where you get the low \
        pressure area underneath that main plane that is where the lowest pressure would be right underneath \
        the throat of that forward main plane";

    #[test]
    fn aligns_a_shifted_sample() {
        // The transcript's copy had 104 s more ads before this point.
        let transcript = cues_from(TALK, 1000.0 + 104.0, 3.0, 8);
        // Whisper heard the same talk at 1000 s, cut into different segments, with a slip.
        let sample = cues_from(&TALK.replace("you know ", ""), 1000.0, 2.0, 5);
        let off = align(&transcript, &sample, 0.0, 900.0).expect("aligned");
        assert!((off - 104.0).abs() < 3.0, "{off}");
        // Unrelated audio (an ad) doesn't match.
        let ad = cues_from(
            "try our new mattress tonight with code podcast for twenty percent off",
            1000.0,
            2.0,
            5,
        );
        assert_eq!(align(&transcript, &ad, 0.0, 900.0), None);
    }

    #[test]
    fn maps_times_through_anchors() {
        let mut t = Transcript::new(Source::PocketCasts, cues_from(TALK, 0.0, 3.0, 8));
        assert_eq!(t.offset_at(50.0), 0.0);
        t.set_anchor(100.0, 104.0);
        t.set_anchor(600.0, 30.0); // a shorter ad break later
        assert_eq!(t.offset_at(50.0), 104.0); // before the first anchor: first offset
        assert_eq!(t.offset_at(300.0), 104.0);
        assert_eq!(t.offset_at(700.0), 30.0);
        assert_eq!(t.to_audio(304.0), 200.0);
        assert_eq!(t.to_audio(730.0), 700.0);
    }

    #[test]
    fn picks_readable_offers_publisher_first() {
        let ep = json!({"transcripts":[{"url":"https://x/t.html","type":"text/html"},{"url":"https://x/t.srt","type":"application/srt"}],
            "pocket_casts_transcripts":[{"url":"https://x/g.vtt","type":"text/vtt"}]});
        let o = offers(&ep);
        assert_eq!(o.len(), 2);
        assert_eq!(o[0].source, Source::Publisher);
        assert_eq!(o[1].source, Source::PocketCasts);
    }
}
